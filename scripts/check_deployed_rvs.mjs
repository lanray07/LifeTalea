import {readFileSync,writeFileSync} from 'node:fs';
import {createPublicKey,verify} from 'node:crypto';
import assert from 'node:assert/strict';
const base='https://guigiqacxpvcxrnajvlz.supabase.co/functions/v1/lifetalea-receipts';
const health=await fetch(base+'/health',{signal:AbortSignal.timeout(15000)});
assert.equal(health.status,200);assert.equal((await health.json()).ready,true);
const response=await fetch(base+'/v1/verify',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({userId:'lifetalea-deployment-invalid-user',receiptId:'lifetalea-deployment-invalid-receipt'}),signal:AbortSignal.timeout(15000)});
assert.equal(response.status,200);
const {assertion}=await response.json();const [data,signature]=assertion.split('.');
const pin=JSON.parse(readFileSync('server/receipt-verifier/supabase/public-signing-key.json')).publicKeySpkiBase64;
assert(verify('RSA-SHA256',Buffer.from(data),createPublicKey({key:Buffer.from(pin,'base64'),format:'der',type:'spki'}),Buffer.from(signature,'base64url')));
const payload=JSON.parse(Buffer.from(data,'base64url'));
assert.equal(payload.environment,'production');assert.equal(payload.active,false);assert.equal(payload.reason,'invalid_receipt');
assert.equal(payload.aud,'com.lifetalea.app');assert.equal(payload.sku,'com.lifetalea.premium');
assert.equal(payload.sub,'lifetalea-deployment-invalid-user');assert.equal(payload.receiptId,'lifetalea-deployment-invalid-receipt');
assert(payload.iat<=Date.now()+300000&&payload.exp>Date.now());
delete payload.sub;delete payload.receiptId;
const report={observedAt:new Date().toISOString(),endpoint:base+'/v1/verify',healthStatus:200,status:response.status,signatureValid:true,payload,scope:'Synthetic invalid identifiers against production Amazon RVS; no purchase, LAT or real customer receipt tested'};
writeFileSync('deliverables/reports/amazon-supabase-deployment.json',JSON.stringify(report,null,2)+'\n');
console.log('Deployed HTTPS health and production signed invalid-receipt rejection: PASS');
